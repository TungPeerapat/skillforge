"""Upgrade a generated skill with verified knowledge.

The existing ``.skills/project-runner`` (or a fresh bundle) is extended in
place: learned references are added, a concise Verification section is
inserted into SKILL.md, and ``.skillforge.json`` records the new verification
state and file hashes. No new skill is created when one already exists, and
skills that were not generated by SkillForge are refused unless ``--force``.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from skillforge.errors import ExampleError, NotFoundError, SkillExistsError, SkillForgeError
from skillforge.learning.generalize import (
    render_troubleshooting,
    render_verified_workflow,
    replace_verification_section,
    verification_section,
)
from skillforge.models import (
    MANIFEST_FILENAME,
    LearnedWorkflow,
    LearningSession,
    SkillBundle,
    SkillFile,
    SkillManifest,
    SkillVerification,
    UpgradeResult,
    VerificationStatus,
)
from skillforge.skills.store import read_bundle, write_bundle
from skillforge.utils.fs import sha256_text

SKILL_NAME = "project-runner"


def render_learned_files(workflow: LearnedWorkflow) -> list[SkillFile]:
    """References produced from a learned workflow (deterministic order)."""
    files = [render_verified_workflow(workflow)]
    troubleshooting = render_troubleshooting(workflow)
    if troubleshooting is not None:
        files.append(troubleshooting)
    return files


def _verified_metadata(session: LearningSession, workflow: LearnedWorkflow) -> SkillVerification:
    fingerprint = session.plan.fingerprint
    if fingerprint is None or not fingerprint.workflow_fingerprint:
        raise ExampleError(
            "cannot mark a skill VERIFIED without a repository fingerprint",
            hint="the execution plan must be built by `skillforge learn`",
        )
    return SkillVerification(
        status=VerificationStatus.VERIFIED,
        method="execution",
        session_id=session.id,
        verified_at=workflow.verified_at,
        fingerprint=fingerprint,
        summary=(
            f"Verified by controlled execution on "
            f"{workflow.verified_at.date().isoformat()} "
            f"({len(workflow.steps)} step(s), session {session.id})"
        ),
    )


def upgrade_skill(
    skill_dir: Path,
    *,
    session: LearningSession,
    workflow: LearnedWorkflow,
    force: bool = False,
) -> UpgradeResult:
    """Write verified knowledge into an existing project-runner skill."""
    if not (skill_dir / "SKILL.md").is_file():
        raise NotFoundError(
            f"No generated project-runner skill found at {skill_dir}",
            hint="run `skillforge generate <repository> project-runner` first",
        )
    stored = read_bundle(skill_dir)
    if stored.manifest is None and not force:
        raise SkillExistsError(
            f"{skill_dir} was not generated by SkillForge; refusing to modify it",
            hint="pass --force to upgrade it anyway, or regenerate with `skillforge generate`",
        )
    old_paths = set(stored.bundle.files)
    learned_files = render_learned_files(workflow)
    files = dict(stored.bundle.files)
    for file in learned_files:
        files[file.path] = file
    # ``split_frontmatter`` keeps the newline that follows the closing ``---``
    # while ``skill_md()`` adds one; normalizing here keeps rewrites idempotent
    # instead of growing a blank line on every upgrade.
    body = stored.bundle.body
    if body.startswith("\n"):
        body = body[1:]
    body = replace_verification_section(body, verification_section(workflow))
    bundle = SkillBundle(metadata=stored.bundle.metadata, body=body, files=files)
    contents = bundle.all_contents()
    if stored.manifest is not None:
        manifest = stored.manifest.model_copy(
            update={
                "file_hashes": {path: sha256_text(text) for path, text in contents.items()},
                "verification": _verified_metadata(session, workflow),
            }
        )
    else:
        manifest = SkillManifest(
            skill=SKILL_NAME,
            title=stored.bundle.metadata.name,
            generated_at=datetime.now(UTC),
            source_repository=session.repository,
            file_hashes={path: sha256_text(text) for path, text in contents.items()},
            verification=_verified_metadata(session, workflow),
            warnings=["manifest was created by `skillforge learn --force`"],
        )
    try:
        write_bundle(bundle, skill_dir, manifest=manifest, overwrite=True)
    except SkillForgeError:  # pragma: no cover - permissions/race
        raise
    created = sorted(file.path for file in learned_files if file.path not in old_paths)
    updated = sorted(file.path for file in learned_files if file.path in old_paths)
    return UpgradeResult(
        skill=SKILL_NAME,
        directory=str(skill_dir),
        created_files=[*created, MANIFEST_FILENAME],
        updated_files=["SKILL.md", *updated],
        status=VerificationStatus.VERIFIED,
        session_id=session.id,
        notes=[f"learned workflow: {len(workflow.steps)} verified step(s)"],
    )


__all__ = ["SKILL_NAME", "render_learned_files", "upgrade_skill"]
